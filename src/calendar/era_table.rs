/// 按年号名称查找纪年记录
///
/// 返回所有匹配的年号记录（同名年号可能出现在多个朝代）。
/// 例如 `find_era("中兴")` 可能返回南北朝多个政权的中兴年号。
pub fn find_era(name: &str) -> Vec<&'static EraRecord> {
    ERA_TABLE.iter().filter(|r| r.era == name).collect()
}

