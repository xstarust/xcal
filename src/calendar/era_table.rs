//! 中国历史纪年表
//!
//! 数据来源与局限：
//!
//! - 本表数据经寿星万年历（sxwnl）作者许剑伟先生整理、校验并数字化。
//! - 主体（约 420 年至今）：万国鼎《中国历史纪年表》。南北朝及以后的帝王年号基本完整。
//! - 早期（约 -2069 ~ 420 年）：由"中华农历论坛" ldlcau 先生补充提供的年号数据。
//!
//! 已知限制：
//! - 部分朝代存在多组帝王并立（如三国、南北朝），本表仅收录主要政权年号。
//! - 早期年号的起止年份依赖考古考证，可能存在 ±数年误差。
//! - 公元 420 年以前的年号数据未经学术权威逐条确认，仅作为参考。
//!
//! 格式：er!(起始年, 持续年, 朝代, 皇帝, 年号)

macro_rules! er {
    ($s:expr, $d:expr, $dy:expr, $em:expr, $er:expr) => {
        EraRecord {
            start: $s,
            duration: $d,
            dynasty: $dy,
            emperor: $em,
            era: $er,
        }
    };
}

