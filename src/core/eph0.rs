/// 度转弧度
fn rad(x: f64) -> f64 {
    x * DEG_TO_RAD
}

/// 归一化角度到 [0, 360)
fn norm_deg(x: f64) -> f64 {
    x.rem_euclid(360.0)
}

/// 计算太阳真黄经（度）
///
/// 基于 VSOP87 地球黄经傅里叶级数。
/// 6 层余弦级数 (L0~L5) × t_k^i，t_k = 儒略千年数。
/// 精度约 0.1 角秒。
pub fn sun_longitude_deg(jd: f64) -> f64 {
    let t = (jd - J2000) / DAYS_PER_CENTURY; // 儒略世纪
    let tk = t / 10.0; // 儒略千年
    let tk2 = tk * tk;
    let tk3 = tk2 * tk;

    // 6 层余弦级数求和：layer_i × tkⁱ
    let mut v = 0.0;
    let mut tn = 1.0;
    let layers: [&[[f64; 3]]; 6] = [&E_L0, &E_L1, &E_L2, &E_L3, &E_L4, &E_L5];
    for layer in layers {
        let mut sum = 0.0;
        for item in layer {
            sum += item[0] * (item[1] + tk * item[2]).cos();
        }
        v += sum * tn;
        tn *= tk;
    }

    // 地球质心→地心修正 + 岁差微调（单位：弧度）
    //
    // VSOP87 计算的是太阳系质心坐标，需要转到地心。
    // 同时 IAU 2000 岁差模型对早期公式修正约 -2.9965"/tjy。
    // 当 t=0(J2000) 时此项值 ≈ -0.0728/rad ≈ -0.015"，可忽略。
    // 当 t=1(3000 年) 时累积约 -2.77"/千年。
    v += (-0.0728 - 2.7702 * tk - 1.1019 * tk2 - 0.0996 * tk3) / 206264.80624709636;

    // 太阳光行差修正
    // 地球公转速度导致太阳视位置偏移
    let m = -0.043126 + 628.301955 * t - 0.000002732 * t * t;
    let e = 0.016708634 - 0.000042037 * t - 0.0000001267 * t * t;
    let aberration = -20.49552 * (1.0 + e * m.cos()) / 3600.0 * DEG_TO_RAD;
    v += aberration;

    // 章动修正（IAU 2000B 77 项）: 自转轴晃动引起的真实黄经摆动，幅度 ±17"
    v += nutation_longitude(jd);

    // 转为度，加 π 使 J2000.0 太阳黄经 ≈ 280.46°
    let deg = (v + PI) * RAD_TO_DEG;
    norm_deg(deg)
}

/// 计算太阳黄经（弧度）
pub fn sun_longitude(jd: f64) -> f64 {
    rad(sun_longitude_deg(jd))
}

/// 计算月亮黄经（度）
///
/// 基于 ELP/MPP02 傅里叶级数（余弦 + 泊松项）。
/// - ML0（442 项）× t⁰
/// - ML1（149 项）× t¹
/// - ML2（34 项）× t²
/// - ML3（2 项）× t³
///   精度约 0.0003°（1 角秒）
pub fn moon_longitude_deg(jd: f64) -> f64 {
    let t = (jd - J2000) / DAYS_PER_CENTURY;
    let t2 = t * t;
    let t3 = t2 * t;
    let t4 = t3 * t;
    let t5 = t4 * t;

    // === 月亮平黄经（转换到度）===
    // rad = 206264.80624709636 arcsec/rad, 所以 3.81034409 rad = 218.3°
    let l0 = 3.81034409 + 8399.684730072 * t - 3.319e-05 * t2 + 3.11e-08 * t3 - 2.033e-10 * t4;
    let l0_deg = l0 * RAD_TO_DEG;
    // 岁差（角秒转度）
    let prec_deg =
        (5028.792262 * t + 1.1124406 * t2 + 0.00007699 * t3 - 0.000023479 * t4 - 0.0000000178 * t5)
            / 3600.0;

    // === 傅里叶级数求和（角秒转度）===
    let t2s = t2 / 1e4;
    let t3s = t3 / 1e8;
    let t4s = t4 / 1e8;
    let arcsec_to_deg = 1.0 / 3600.0;

    let mut v = l0_deg + prec_deg;
    v += fourier_sum(&ML0, 1.0, t, t2s, t3s, t4s) * arcsec_to_deg;
    v += fourier_sum(&ML1, t, t, t2s, t3s, t4s) * arcsec_to_deg;
    v += fourier_sum(&ML2, t2, t, t2s, t3s, t4s) * arcsec_to_deg;
    v += fourier_sum(&ML3, t3, t, t2s, t3s, t4s) * arcsec_to_deg;

    // 光行差: -3.4e-6 rad → 度
    v -= 3.4e-6 * RAD_TO_DEG;

    // 章动修正（IAU 2000B 77 项）
    v += nutation_longitude(jd) * RAD_TO_DEG;

    norm_deg(v)
}

/// 对一层傅里叶项求和：Σ A * tn * cos(b + t*c + t2s*d + t3s*e + t4s*f)
///
/// # Arguments
/// * `terms` - 傅里叶项数组 [[A, b, c, d, e, f]; N]
/// * `tn` - 该层的 t^n 权重
fn fourier_sum<const N: usize>(
    terms: &[[f64; 6]; N],
    tn: f64,
    t: f64,
    t2s: f64,
    t3s: f64,
    t4s: f64,
) -> f64 {
    let mut sum = 0.0;
    for &[a, b, c, d, e, f] in terms {
        let arg = b + t * c + t2s * d + t3s * e + t4s * f;
        sum += a * tn * arg.cos();
    }
    sum
}

/// 计算月亮黄经（弧度）
pub fn moon_longitude(jd: f64) -> f64 {
    rad(moon_longitude_deg(jd))
}

/// 日月黄经差（度，归一化到 [-180, 180)）
pub fn moon_sun_delta_deg(jd: f64) -> f64 {
    let mut diff = moon_longitude_deg(jd) - sun_longitude_deg(jd);
    diff = diff.rem_euclid(360.0);
    if diff > 180.0 { diff - 360.0 } else { diff }
}

