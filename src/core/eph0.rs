    #[test]
    fn verify_moon_accuracy() {
        let cases = [
            (2451545.0, 223.318900, "J2000.0"),
            (2460310.5, 155.984406, "2024-01-01"),
            (2460482.5, 257.071353, "2024-06-21"),
            (2460576.5, 67.961430, "2024-09-23"),
        ];
        for &(jd, ref_val, label) in &cases {
            let calx_val = moon_longitude_deg(jd);
            let diff = (calx_val - ref_val).abs();
            assert!(
                diff < 0.005,
                "{}: xcal={:.6}°, ref={:.6}°, diff={:.6}°",
                label,
                calx_val,
                ref_val,
                diff
            );
        }
    }
